// Synthetic sliced G-code in the shape real slicers write it, for tests.
// The marker lines copy what Bambu Studio 2.x and PrusaSlicer 2.x actually emit.

const f3 = (v) => v.toFixed(3);

function circle(cx, cy, r, n, ccw, start = 0) {
  const pts = [];
  for (let k = 0; k <= n; k++) {
    const a = start + ((ccw ? 1 : -1) * 2 * Math.PI * k) / n;
    pts.push([cx + r * Math.cos(a), cy + r * Math.sin(a)]);
  }
  return pts;
}

function square(cx, cy, h) {
  return [[cx - h, cy - h], [cx + h, cy - h], [cx + h, cy + h], [cx - h, cy + h], [cx - h, cy - h]];
}

/** Bambu-style: M83, `; FEATURE:` markers, M624/M625 object labels, wipes after walls. */
export function bambuGcode({ layers = 20, layerH = 0.2 } = {}) {
  const L = [
    "; HEADER_BLOCK_START",
    "; BambuStudio 02.05.00.66",
    "; total layer number: " + layers,
    "; HEADER_BLOCK_END",
    "; EXECUTABLE_BLOCK_START",
    "M73 P0 R10",
    "G90",
    "M83",
    "G1 Z5 F1200",
  ];
  const loop = (pts, e) => {
    L.push(`G1 X${f3(pts[0][0])} Y${f3(pts[0][1])} F42000`);
    L.push("G1 F3000");
    for (let k = 1; k < pts.length; k++) {
      const d = Math.hypot(pts[k][0] - pts[k - 1][0], pts[k][1] - pts[k - 1][1]);
      L.push(`G1 X${f3(pts[k][0])} Y${f3(pts[k][1])} E${(d * e).toFixed(5)}`);
      // Overhang slowdowns show up as feed-only lines in the middle of a wall.
      if (k === Math.floor(pts.length / 2)) L.push("G1 F2400");
    }
  };
  for (let n = 1; n <= layers; n++) {
    const z = n * layerH;
    L.push("; CHANGE_LAYER", `; Z_HEIGHT: ${z.toFixed(1)}`, `; LAYER_HEIGHT: ${layerH}`, "G1 E-.8 F1800");
    L.push(`; layer num/total_layer_count: ${n}/${layers}`, `M73 L${n}`, `M991 S0 P${n - 1} ;notify layer change`);
    L.push(`G1 Z${f3(z)} F1200`);

    // Object 1: a cylinder, r=15 at (100,100). Inner wall then outer wall (CCW), then a wipe.
    L.push("M624 AQAAAAAAAAA=", "; start printing object, unique label id: 15");
    L.push("; FEATURE: Inner wall", "; LINE_WIDTH: 0.45");
    loop(circle(100, 100, 14.6, 96, true), 0.033);
    L.push("; FEATURE: Outer wall", "; LINE_WIDTH: 0.42");
    loop(circle(100, 100, 15, 96, true), 0.031);
    L.push("; WIPE_START", "G1 F24000", "G1 X114.9 Y101 E-.4", "; WIPE_END", "G1 E-.4 F1800");
    L.push("; stop printing object, unique label id: 15", "M625");

    // Object 2: a 20 mm square with a round hole. The hole's outer wall runs CW.
    L.push("M624 AgAAAAAAAAA=", "; start printing object, unique label id: 22");
    L.push("; FEATURE: Outer wall", "; LINE_WIDTH: 0.42");
    loop(square(160, 100, 10), 0.031);
    L.push("; FEATURE: Outer wall");
    loop(circle(160, 100, 4, 48, false), 0.031);
    L.push("; FEATURE: Sparse infill", `G1 X152 Y92 E.5`, `G1 X168 Y108 E.7`);
    L.push("; stop printing object, unique label id: 22", "M625");
  }
  L.push("; EXECUTABLE_BLOCK_END", "M400", "");
  return L.join("\n");
}

/** Prusa-style: M82 absolute E, `;TYPE:` markers, an outer wall drawn with G2/G3 arcs. */
export function prusaGcode({ layers = 6, layerH = 0.2 } = {}) {
  const L = ["; generated by PrusaSlicer 2.8.0", "G90", "M82", "G92 E0"];
  let e = 0;
  for (let n = 1; n <= layers; n++) {
    const z = n * layerH;
    L.push(";LAYER_CHANGE", `;Z:${z.toFixed(1)}`, `;HEIGHT:${layerH}`, `G1 Z${f3(z)} F720`);
    L.push(";TYPE:External perimeter", ";WIDTH:0.45");
    L.push("G1 X120 Y100 F9000");
    L.push("G1 F1800");
    // Two half circles as arcs around (100,100), r=20, CCW.
    e += Math.PI * 20 * 0.03;
    L.push(`G3 X80 Y100 I-20 J0 E${e.toFixed(5)}`);
    e += Math.PI * 20 * 0.03;
    L.push(`G3 X120 Y100 I20 J0 E${e.toFixed(5)}`);
    L.push(";TYPE:Solid infill", `G1 X100 Y100 E${(e += 0.4).toFixed(5)}`);
    L.push("G1 E" + (e - 0.8).toFixed(5) + " F2100");
    e -= 0.8;
  }
  L.push("M84", "");
  return L.join("\r\n");
}

/**
 * A lamp shade cross-section: an outer shell (r 40, wall to r 38) around a socket tube
 * (r 8, bore r 5), all one object. Per layer the outer walls are: shell outside (depth 0),
 * shell inside (depth 1, a hole), tube outside (depth 2, an island), tube bore (depth 3).
 */
export function lampGcode({ layers = 4, layerH = 0.2 } = {}) {
  const L = ["; BambuStudio 02.05.00.66", "G90", "M83"];
  const loop = (pts) => {
    L.push(`G1 X${f3(pts[0][0])} Y${f3(pts[0][1])} F42000`);
    for (let k = 1; k < pts.length; k++) {
      const d = Math.hypot(pts[k][0] - pts[k - 1][0], pts[k][1] - pts[k - 1][1]);
      L.push(`G1 X${f3(pts[k][0])} Y${f3(pts[k][1])} E${(d * 0.031).toFixed(5)}`);
    }
  };
  for (let n = 1; n <= layers; n++) {
    L.push("; CHANGE_LAYER", `; Z_HEIGHT: ${(n * layerH).toFixed(1)}`, `G1 Z${f3(n * layerH)} F1200`);
    L.push("; start printing object, unique label id: 1");
    for (const [r, ccw] of [[40, true], [38, false], [8, true], [5, false]]) {
      L.push("; FEATURE: Outer wall");
      loop(circle(128, 128, r, 120, ccw));
    }
    L.push("; stop printing object, unique label id: 1");
  }
  L.push("");
  return L.join("\n");
}

/**
 * A lamp base whose cable slot runs from the rim in to a central tube, as one outline: rim arc
 * (r 40), slot side in, around the tube (r 8) the long way, slot side out. Bambu interrupts the
 * wall with M106 fan lines at the slot corners and an M73 progress line on the rim, which is
 * how the real KDI lamp file arrives.
 */
export function slottedBaseGcode({ layers = 3, layerH = 0.2, half = 2 } = {}) {
  const c = 128, R = 40, r = 8;
  const L = ["; BambuStudio 02.05.00.66", "G90", "M83"];
  const aR = Math.asin(half / R), ar = Math.asin(half / r);
  const arc = (rad, from, to, n) => Array.from({ length: n + 1 }, (_, k) => {
    const a = from + ((to - from) * k) / n;
    return [c + rad * Math.cos(a), c + rad * Math.sin(a)];
  });
  for (let n = 1; n <= layers; n++) {
    L.push("; CHANGE_LAYER", `; Z_HEIGHT: ${(n * layerH).toFixed(1)}`, `G1 Z${f3(n * layerH)} F1200`);
    // Slot points along -Y: rim CCW from the slot's right edge round to its left edge.
    const rim = arc(R, -Math.PI / 2 + aR, (3 * Math.PI) / 2 - aR, 200);
    const tube = arc(r, (3 * Math.PI) / 2 - ar, -Math.PI / 2 + ar, 60); // CW round the tube
    const pts = [...rim, ...tube, rim[0]];
    L.push(`G1 X${f3(pts[0][0])} Y${f3(pts[0][1])} F42000`, "; FEATURE: Outer wall", "; LINE_WIDTH: 0.42", "G1 F3000");
    for (let k = 1; k < pts.length; k++) {
      const d = Math.hypot(pts[k][0] - pts[k - 1][0], pts[k][1] - pts[k - 1][1]);
      L.push(`G1 X${f3(pts[k][0])} Y${f3(pts[k][1])} E${(d * 0.031).toFixed(5)}`);
      if (k === 100) L.push("M73 P50 R10");
      if (k === rim.length - 1 || k === rim.length) L.push("M106 S229.5");
    }
  }
  L.push("");
  return L.join("\n");
}
